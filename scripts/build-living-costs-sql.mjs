// Builds supabase/data/living_costs.sql from data/reference/living-costs.json.
//   node scripts/build-living-costs-sql.mjs
// Run the result in Supabase -> SQL Editor. It only fills the "cost of living" and the official link of a country;
// everything else in the country row (currency, work rules, status) is kept as it is. Safe to run again.
import { readFileSync, writeFileSync } from 'node:fs';

const data = JSON.parse(readFileSync('data/reference/living-costs.json', 'utf8'));
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const lines = [
  '-- YourHEI: monthly living money that countries officially require for a study visa (generated by scripts/build-living-costs-sql.mjs).',
  '-- A minimum set by the authorities, not an average of real spending. Safe to run again.',
];
for (const c of data.items) {
  if (!/^[A-Z]{2}$/.test(c.country) || !/^[A-Z]{3}$/.test(c.currency) || !/^https:\/\//.test(c.url)) throw new Error(`bad row: ${c.country}`);
  const list = c.cities.map((x) => {
    if (!(x.amount > 0)) throw new Error(`bad amount: ${c.country}`);
    return { city: { en: x.en }, amount_per_month: x.amount, currency: c.currency };
  });
  const urls = { cost_of_living: c.url };
  lines.push(
    `insert into public.country_data (country, currency, cost_of_living, official_urls, status, verified_at) values (${q(c.country)}, ${q(c.currency)}, ${q(JSON.stringify(list))}::jsonb, ${q(JSON.stringify(urls))}::jsonb, 'published', now())` +
      ` on conflict (country) do update set cost_of_living = excluded.cost_of_living, official_urls = coalesce(public.country_data.official_urls, '{}'::jsonb) || excluded.official_urls, currency = coalesce(public.country_data.currency, excluded.currency);`,
  );
}
writeFileSync('supabase/data/living_costs.sql', lines.join('\n') + '\n');
console.log(`${data.items.length} countries written.`);
