// Builds supabase/data/scholarships_national.sql from data/scholarships/national.json.
//   node scripts/build-scholarships-sql.mjs
// Run the resulting file in Supabase -> SQL Editor (after migration 0011). It replaces only the country-level
// scholarships, so it is safe to run again and never touches the scholarships of single institutions.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const data = JSON.parse(readFileSync('data/scholarships/national.json', 'utf8'));
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;
const COVERS = ['tuition', 'living', 'full', 'partial'];

const lines = [
  '-- YourHEI: government and international scholarships (generated by scripts/build-scholarships-sql.mjs).',
  '-- Run AFTER supabase/migrations/0011_community.sql. Safe to run again.',
  "delete from public.scholarships where scope = 'country';",
];
for (const s of data.items) {
  if (!COVERS.includes(s.covers)) throw new Error(`bad covers: ${s.covers}`);
  if (!/^https:\/\//.test(s.url)) throw new Error(`url must be https: ${s.url}`);
  if (!s.names.en || !s.names.ru) throw new Error(`names need en and ru: ${JSON.stringify(s.names)}`);
  const names = { original: s.names.en, ...s.names };
  lines.push(
    `insert into public.scholarships (scope, host_country, names, covers, funder, levels, eligibility, url, status, verified_at, accessed_at) values ('country', ${q(s.country)}, ${j(names)}, ${q(s.covers)}, ${j(s.funder)}, ${arr(s.levels)}, ${j(s.eligibility)}, ${q(s.url)}, 'published', now(), ${q(data.accessed)});`,
  );
}
mkdirSync('supabase/data', { recursive: true });
writeFileSync('supabase/data/scholarships_national.sql', lines.join('\n') + '\n');
console.log(`${data.items.length} scholarships written.`);
