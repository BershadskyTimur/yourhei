// Builds the country reference data used by registration:
//   data/reference/countries.json        (read by the site)
//   data/reference/regions.json          (read by the site)
//   supabase/migrations/0003_reference_data.sql  (paste into the Supabase SQL editor)
// Run: node scripts/build-reference.mjs
// ISO 3166-1 codes come from the i18n-iso-countries package; the Europe / Asia split into
// sub-regions follows UN M49 (https://unstats.un.org/unsd/methodology/m49/). Please re-check.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import countries from 'i18n-iso-countries';

const split = (s) => s.trim().split(/\s+/);

const SUBREGIONS = {
  'eastern-europe': ['europe', split('BY BG CZ HU MD PL RO RU SK UA')],
  'northern-europe': ['europe', split('AX DK EE FO FI GG IS IE IM JE LV LT NO SJ SE GB')],
  'southern-europe': ['europe', split('AL AD BA HR GI GR VA IT MT ME MK PT SM RS SI ES')],
  'western-europe': ['europe', split('AT BE FR DE LI LU MC NL CH')],
  'central-asia': ['asia', split('KZ KG TJ TM UZ')],
  // Taiwan is not a separate M49 entry; it is listed under Eastern Asia as an ISO 3166-1 code.
  'eastern-asia': ['asia', split('CN HK MO JP KP KR MN TW')],
  'south-eastern-asia': ['asia', split('BN KH ID LA MY MM PH SG TH TL VN')],
  'southern-asia': ['asia', split('AF BD BT IN IR LK MV NP PK')],
  'western-asia': ['asia', split('AM AZ BH CY GE IQ IL JO KW LB OM PS QA SA SY TR AE YE')],
};

// SPEC.md section 5: working region "Caucasus, Central Asia and Eastern Europe".
const CAUCASUS_CA_EE = split('AM AZ BY GE KZ KG MD RU TJ TM UZ UA');

// XK (Kosovo) is a user-assigned code, not part of ISO 3166-1; left out by the owner's decision.
const all = Object.keys(countries.getAlpha2Codes())
  .filter((c) => c !== 'XK')
  .sort();
const placed = new Map();
for (const [sub, [region, codes]] of Object.entries(SUBREGIONS)) {
  for (const c of codes) {
    if (placed.has(c)) throw new Error(`${c} is in two sub-regions`);
    placed.set(c, { region, subregion: sub });
  }
}
// Every listed code must be a real ISO code.
for (const c of placed.keys()) if (!all.includes(c)) throw new Error(`Unknown ISO code ${c}`);
for (const c of CAUCASUS_CA_EE) if (!placed.has(c)) throw new Error(`${c} has no sub-region`);

const list = all.map((code) => ({
  code,
  region: placed.get(code)?.region ?? 'other',
  subregion: placed.get(code)?.subregion ?? null,
}));

const regions = [
  { id: 'caucasus-ca-ee', countries: CAUCASUS_CA_EE },
  { id: 'europe', countries: list.filter((c) => c.region === 'europe').map((c) => c.code) },
  { id: 'asia', countries: list.filter((c) => c.region === 'asia').map((c) => c.code) },
];

mkdirSync('data/reference', { recursive: true });
writeFileSync('data/reference/countries.json', JSON.stringify(list, null, 1) + '\n');
writeFileSync('data/reference/regions.json', JSON.stringify(regions, null, 1) + '\n');

const th = JSON.parse(readFileSync('data/reference/age-thresholds.json', 'utf8'));
const q = (s) => (s == null ? 'null' : `'${s}'`);

const sql = `-- Reference data for registration. Generated by scripts/build-reference.mjs - do not edit by hand.
-- Safe to run again.

insert into public.countries (code, region, subregion) values
${list.map((c) => `  ('${c.code}', '${c.region}', ${q(c.subregion)})`).join(',\n')}
on conflict (code) do update set region = excluded.region, subregion = excluded.subregion;

insert into public.regions (id, sort_order) values
${regions.map((r, i) => `  ('${r.id}', ${i + 1})`).join(',\n')}
on conflict (id) do nothing;

delete from public.region_countries;
insert into public.region_countries (region_id, country) values
${regions.flatMap((r) => r.countries.map((c) => `  ('${r.id}', '${c}')`)).join(',\n')};

insert into public.country_age_thresholds (country, min_age, needs_legal_review) values
${Object.entries(th.overrides)
  .map(([c, a]) => `  ('${c}', ${a}, true)`)
  .join(',\n')}
on conflict (country) do update set min_age = excluded.min_age;

-- Default for every other country (${th.default}) lives in the function public.min_age_for().
`;
writeFileSync('supabase/migrations/0003_reference_data.sql', sql);
console.log(`${list.length} countries, regions:`, regions.map((r) => `${r.id}=${r.countries.length}`).join(', '));
